// Applies nutrition labels transcribed from photos (research/<topic>/raw-data/labels_<date>.json)
// as the owner through RLS, in one atomic DO statement, like research/chocolate/import.mjs:
//
//   node research/apply-labels.mjs <owner-uuid> <labels.json> <out.sql> [--dry-run]
//   pnpm exec supabase db query --file <out.sql>                   (local)
//   pnpm exec supabase db query --file <out.sql> --remote --yes    (hosted, after approval)
//
// Each entry adds a source and replaces the product's whole nutrition row (nutrients it omits become
// null). The source is the label by default; a product without a nutrition table can instead use a
// reference database: "source": { "kind": "bibliographic", "title": ..., "url": ... }.
// A product is found by name + package_size + unit and must exist once.
import { readFileSync, writeFileSync } from 'node:fs';

const [owner, labelsPath, outPath, mode] = process.argv.slice(2);
if (!/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/.test(owner ?? '') || !labelsPath || !outPath) {
  throw new Error('usage: node research/apply-labels.mjs <owner-uuid> <labels.json> <out.sql> [--dry-run]');
}
const doc = JSON.parse(readFileSync(labelsPath, 'utf8'));
const NUTRIENTS = ['energy_kcal', 'fat_g', 'saturated_fat_g', 'carbohydrates_g', 'sugars_g', 'fiber_g', 'protein_g', 'sodium_mg'];

const fail = (msg) => { throw new Error(msg); };
const lit = (v) => {
  if (v == null) return 'null';
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : fail(`bad number ${v}`);
  return `'${String(v).replaceAll("'", "''")}'`;
};

const body = [`select id into strict proj from public.research_projects where title = ${lit(doc.project)};`];
for (const l of doc.labels) {
  const p = l.product;
  body.push(`select id into strict pid from public.products where name = ${lit(p.name)} and package_size = ${lit(p.package_size)} and unit = ${lit(p.unit)};`);
  const source = l.source ?? { kind: 'label', title: `Etiqueta: ${p.name}` };
  const notes = [l.notes, l.photo && `Foto: ${l.photo}.`].filter(Boolean).join(' ');
  body.push(`insert into public.sources (project_id, kind, title, url, accessed_on, notes) values (proj, ${lit(source.kind)}, ${lit(source.title)}, ${lit(source.url)}, ${lit(doc.observed_on)}, ${lit(notes)}) returning id into src;`);
  if (l.values) {
    const unknown = Object.keys(l.values).filter((k) => !NUTRIENTS.includes(k));
    if (unknown.length) fail(`${p.name}: no column for ${unknown.join(', ')}`);
    if (!(l.basis_quantity > 0)) fail(`${p.name}: basis_quantity required`);
    body.push(
      `insert into public.product_nutrition (product_id, basis_quantity, ${NUTRIENTS.join(', ')}, source_id) ` +
      `values (pid, ${lit(l.basis_quantity)}, ${NUTRIENTS.map((c) => lit(l.values[c])).join(', ')}, src) ` +
      `on conflict (product_id) do update set basis_quantity = excluded.basis_quantity, ` +
      `${NUTRIENTS.map((c) => `${c} = excluded.${c}`).join(', ')}, source_id = excluded.source_id;`,
    );
  }
  if (l.product_note) body.push(`update public.products set notes = concat_ws(' ', notes, ${lit(l.product_note)}) where id = pid;`);
}

const report = 'recetas con energía: %/%, con azúcares: %/%';
const out = [
  `-- Generated by research/apply-labels.mjs from ${labelsPath}. Owner: ${owner}. Mode: ${mode === '--dry-run' ? 'dry run (rolled back)' : 'commit'}.`,
  'do $labels$',
  'declare proj uuid; pid uuid; src uuid; e bigint; s bigint; t bigint;',
  'begin',
  `  perform set_config('role', 'authenticated', true);`,
  `  perform set_config('request.jwt.claims', ${lit(JSON.stringify({ sub: owner, role: 'authenticated' }))}, true);`,
  ...body.map((s) => `  ${s}`),
  `  select count(*) filter (where energy_kcal is not null), count(*) filter (where sugars_g is not null), count(*)`,
  `    into e, s, t from public.v_formulation_nutrition where project_id = proj;`,
  mode === '--dry-run'
    ? `  raise exception 'DRY RUN OK, nothing saved: ${report}', e, t, s, t;`
    : `  raise notice '${report}', e, t, s, t;`,
  'end',
  '$labels$;',
  '',
].join('\n');
writeFileSync(outPath, out, 'utf8');
console.log(`${doc.labels.length} labels -> ${outPath}`);
