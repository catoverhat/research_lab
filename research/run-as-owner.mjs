// Runs a PL/pgSQL body (a data fix such as research/<topic>/fixes/<date>_<name>.sql) as the owner
// through RLS, in one atomic DO statement, like the importers:
//
//   node research/run-as-owner.mjs <owner-uuid> <body.sql> <out.sql> [--dry-run]
//   pnpm exec supabase db query --file <out.sql>                   (local)
//   pnpm exec supabase db query --file <out.sql> --remote --yes    (hosted, after approval)
//
// The body can use the variable `n bigint`, e.g. `get diagnostics n = row_count;` to check how many
// rows an update touched. Any error discards everything; --dry-run always ends by raising.
import { readFileSync, writeFileSync } from 'node:fs';

const [owner, bodyPath, outPath, mode] = process.argv.slice(2);
if (!/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/.test(owner ?? '') || !bodyPath || !outPath) {
  throw new Error('usage: node research/run-as-owner.mjs <owner-uuid> <body.sql> <out.sql> [--dry-run]');
}
const body = readFileSync(bodyPath, 'utf8');
if (body.includes('$fix$')) throw new Error('the body must not contain $fix$');

const claims = JSON.stringify({ sub: owner, role: 'authenticated' });
writeFileSync(outPath, [
  `-- Generated by research/run-as-owner.mjs from ${bodyPath}. Owner: ${owner}. Mode: ${mode === '--dry-run' ? 'dry run (rolled back)' : 'commit'}.`,
  'do $fix$',
  'declare n bigint;',
  'begin',
  `perform set_config('role', 'authenticated', true);`,
  `perform set_config('request.jwt.claims', '${claims}', true);`,
  body,
  mode === '--dry-run' ? `raise exception 'DRY RUN OK, nothing saved';` : '',
  'end',
  '$fix$;',
  '',
].join('\n'), 'utf8');
console.log(`${bodyPath} -> ${outPath}`);
